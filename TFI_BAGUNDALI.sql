-- Telugu Cinema Analytics Database
-- MySQL 8.0.16+ recommended (CHECK constraints enforced).
-- Seed scope: 100 notable Telugu films released 2000-2025; 2026 is included in the selected period but no 2026 titles are seeded here.
-- Credits are a curated starter dataset. Confirm individual credits against film credits before external/commercial use.
-- Box-office collection figures are intentionally NOT fabricated. Populate box_office only with sourced, territory-specific figures.


CREATE DATABASE tfi_bagundali CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

USE tfi_bagundali;

-- 1. Lookup / master tables
CREATE TABLE directors (
    director_id INT AUTO_INCREMENT PRIMARY KEY,
    director_name VARCHAR(120) NOT NULL UNIQUE,
    country VARCHAR(60) NOT NULL DEFAULT 'India'
) ENGINE=InnoDB;

CREATE TABLE actors (
    actor_id INT AUTO_INCREMENT PRIMARY KEY,
    actor_name VARCHAR(120) NOT NULL UNIQUE,
    primary_industry VARCHAR(60) NOT NULL DEFAULT 'Indian cinema'
) ENGINE=InnoDB;

CREATE TABLE genres (
    genre_id INT AUTO_INCREMENT PRIMARY KEY,
    genre_name VARCHAR(60) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE production_houses (
    production_house_id INT AUTO_INCREMENT PRIMARY KEY,
    production_house_name VARCHAR(150) NOT NULL UNIQUE,
    country VARCHAR(60) NOT NULL DEFAULT 'India'
) ENGINE=InnoDB;

-- 2. Core movie table
CREATE TABLE movies (
    movie_id INT AUTO_INCREMENT PRIMARY KEY,
    movie_title VARCHAR(180) NOT NULL,
    release_year SMALLINT UNSIGNED NOT NULL,
    language VARCHAR(40) NOT NULL DEFAULT 'Telugu',
    director_id INT NOT NULL,
    runtime_minutes SMALLINT UNSIGNED NULL,
    notes VARCHAR(500) NULL,
    CONSTRAINT uq_movie_title_year UNIQUE (movie_title, release_year),
    CONSTRAINT chk_release_year CHECK (release_year BETWEEN 2000 AND 2026),
    CONSTRAINT fk_movies_director FOREIGN KEY (director_id) REFERENCES directors(director_id)
) ENGINE=InnoDB;

-- 3. Bridge tables for many-to-many relationships
CREATE TABLE movie_cast (
    movie_cast_id INT AUTO_INCREMENT PRIMARY KEY,
    movie_id INT NOT NULL,
    actor_id INT NOT NULL,
    character_name VARCHAR(120) NULL,
    role_type VARCHAR(30) NOT NULL DEFAULT 'Cast',
    billing_order TINYINT UNSIGNED NOT NULL DEFAULT 1,
    CONSTRAINT uq_movie_actor UNIQUE (movie_id, actor_id),
    CONSTRAINT fk_cast_movie FOREIGN KEY (movie_id) REFERENCES movies(movie_id) ON DELETE CASCADE,
    CONSTRAINT fk_cast_actor FOREIGN KEY (actor_id) REFERENCES actors(actor_id)
) ENGINE=InnoDB;

CREATE TABLE movie_genres (
    movie_id INT NOT NULL,
    genre_id INT NOT NULL,
    PRIMARY KEY (movie_id, genre_id),
    CONSTRAINT fk_movie_genres_movie FOREIGN KEY (movie_id) REFERENCES movies(movie_id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_genres_genre FOREIGN KEY (genre_id) REFERENCES genres(genre_id)
) ENGINE=InnoDB;

CREATE TABLE movie_production (
    movie_id INT NOT NULL,
    production_house_id INT NOT NULL,
    PRIMARY KEY (movie_id, production_house_id),
    CONSTRAINT fk_movie_production_movie FOREIGN KEY (movie_id) REFERENCES movies(movie_id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_production_house FOREIGN KEY (production_house_id) REFERENCES production_houses(production_house_id)
) ENGINE=InnoDB;

-- 4. Box-office fact table. Values are nullable because reported totals vary by source and territory.
CREATE TABLE box_office (
    collection_id BIGINT AUTO_INCREMENT PRIMARY KEY,
    movie_id INT NOT NULL,
    territory VARCHAR(80) NOT NULL,
    collection_type VARCHAR(40) NOT NULL DEFAULT 'Gross',
    gross_collection_inr DECIMAL(16,2) NULL,
    distributor_share_inr DECIMAL(16,2) NULL,
    source_name VARCHAR(150) NULL,
    source_url VARCHAR(500) NULL,
    reported_on DATE NULL,
    CONSTRAINT uq_movie_territory_type UNIQUE (movie_id, territory, collection_type),
    CONSTRAINT fk_boxoffice_movie FOREIGN KEY (movie_id) REFERENCES movies(movie_id) ON DELETE CASCADE,
    CONSTRAINT chk_gross_nonnegative CHECK (gross_collection_inr IS NULL OR gross_collection_inr >= 0),
    CONSTRAINT chk_share_nonnegative CHECK (distributor_share_inr IS NULL OR distributor_share_inr >= 0)
) ENGINE=InnoDB;

